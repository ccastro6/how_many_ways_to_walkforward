def tab_size():
    f = MC / "summary_procedures.csv"
    if not f.exists():
        print("skip tab_size")
        return
    sp = pd.read_csv(f)
    dep = pd.read_csv(MC / "summary_dependence.csv")
    dgps = ["garch_t", "iid_t"]
    counts = dep[(dep["dgp"] == "garch_t") & (dep["param"] == 0)].iloc[0].to_dict()
    body, recs = "", []
    for pi, (title, procs) in enumerate(SIZE_PANELS):
        if pi:
            body += r"\addlinespace" + "\n"
        body += rf"\multicolumn{{5}}{{@{{}}l}}{{\emph{{{title}}}}} \\" + "\n"
        for key, lab in procs:
            cells = [lab.format(**counts)]
            for d in dgps:
                q = sp[(sp["dgp"] == d) & (sp["procedure"] == key)]
                q = q[q["K"] == (351 if key.startswith("rules") else 56)]
                rr, se = float(q["reject"].iloc[0]), float(q["mc_se"].iloc[0])
                v = f"{100 * rr:.1f}"
                cells += [rf"\textbf{{{v}}}" if rr - 0.05 > 2.58 * se else v, f"({100 * se:.1f})"]
                recs.append(dict(procedure=key, dgp=d, reject=rr, mc_se=se))
            body += row(*cells)
    reps = int(sp[sp["dgp"] == "garch_t"]["reps"].iloc[0])
    tab = (r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrr@{}}" "\n" r"\toprule" "\n"
           + r" & \multicolumn{2}{c}{GARCH(1,1)-$t$ null} & \multicolumn{2}{c}{i.i.d.\ Student-$t$ null} \\" "\n"
           + r"\cmidrule{2-3}\cmidrule{4-5}" "\n"
           + row("Procedure", r"Rejection \%", "(MC s.e.)", r"Rejection \%", "(MC s.e.)")
           + r"\midrule" "\n" + body + r"\bottomrule" "\n" r"\end{tabular*}")
    note = ("Share of simulated markets with no predictability in which the procedure declares, at the nominal 5\\% "
            "level (one-sided), that the strategy beats the benchmark: buy-and-hold (the strategy's return minus the "
            "market's) or cash (the strategy's own excess return). A correct test rejects about 5\\% of the time. "
            f"{reps:,} replications per null; MC s.e.\\ is the Monte Carlo standard error. Bootstrap critical values "
            "use the warp-speed method of Giacomini, Politis and White (2013). Panel D is for reference: each "
            "effective number of designs is computed within each simulated market from the correlation matrix of the "
            "56 difference series (Section~6.1 and Appendix~A); its average over the GARCH null is in "
            "parentheses; the Deflated Sharpe Ratio rejects when it exceeds 0.95. Bold: rate more than 2.58 "
            "standard errors above 5\\%.")
    save("tab_size", tab, note, pd.DataFrame(recs))


# ------------------------------------------------------------------ Table 5: empirical
def tab_empirical():
    s = pd.read_csv(EMP / "summary.csv")
    body, recs = "", []
    panels = (("net", "Panel A. After 10 bp per unit of turnover"), ("gross", "Panel B. Before trading costs"),
              ("gross_lag", "Panel C. Before trading costs, every position taken one day later"))
    for pi, (tag, title) in enumerate(panels):
        if pi:
            body += r"\addlinespace" + "\n"
        body += rf"\multicolumn{{9}}{{@{{}}l}}{{\emph{{{title}}}}} \\" + "\n"
        for smp in ORDER:
            q = s[(s["sample"] == smp) & (s["costs"] == tag)]
            if q.empty:
                continue
            q = q.iloc[0]
            body += row(SAMPLE_NAMES[smp], num(q["best_t"]), fp(q["p_naive_best"]), fp(q["p_maxt"]), fp(q["p_avgt"]),
                        f"{int(q['n_sig_raw'])} / {int(q['n_sig_stepm'])}", num(q["mean_corr_d"]), num(q["n_eff_d"], 1),
                        num(q["pbo"]))
            recs.append(q.to_dict())
    tab = (r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrrcrrr@{}}" "\n" r"\toprule" "\n"
           + r" & \multicolumn{2}{c}{Best of 56 designs} & \multicolumn{2}{c}{All 56 designs} & Signif. & "
             r"\multicolumn{2}{c}{Dependence} & \\" "\n"
           + r"\cmidrule{2-3}\cmidrule{4-5}\cmidrule{7-8}" "\n"
           + row("Series", "$t$", "$p$ naive", "$p$ max-$t$", "$p$ avg-$t$", "naive / StepM", "Corr.", "Eff.\\ no.",
                 "PBO")
           + r"\midrule" "\n" + body + r"\bottomrule" "\n" r"\end{tabular*}")
    note = ("Each walk-forward design picks, in every training window, the rule with the highest Sharpe ratio among the "
            "351 rules of Table~1 and trades it over the next test block. The test is whether the strategy beats "
            "buy-and-hold (returns above T-bills), with Newey--West $t$-statistics. $p$ naive treats the best design as "
            "if it were the only one tried; max-$t$ is the studentised Reality Check over the 56 designs; avg-$t$ tests "
            "the average $t$-statistic across all designs, with critical values from the stationary bootstrap (1,999 "
            "draws). Signif.\\ counts designs with naive $p<0.05$ and with Romano--Wolf StepM adjusted $p<0.05$. "
            "Corr.\\ is the mean pairwise correlation of the 56 daily series of strategy minus buy-and-hold returns "
            "and Eff.\\ no.\\ the participation-ratio effective number of designs computed from it. PBO is the "
            "probability of backtest overfitting from 16-block combinatorially symmetric cross-validation. In Panel C "
            "a signal at the close of day $t$ is traded at the close of day $t+1$, in the training windows and in the "
            "test blocks. Bold: $p<0.05$.")
    save("tab_empirical", tab, note, pd.DataFrame(recs))


# ------------------------------------------------------------------ Table 6: US by period
def tab_eras():
    es = pd.read_csv(EMP / "eras_summary.csv")
    body = ""
    rng_t = lambda q: f"{num(q['min_t'], 1)} to {num(q['max_t'], 1)}"
    for era in ["1930-1959", "1960-1989", "1990-2026"]:
        cells = [era.replace("-", "--")]
        for tag in ("gross", "net"):
            q = es[(es["era"] == era) & (es["costs"] == tag)].iloc[0]
            cells += [rng_t(q), int(q["n_sig_raw"]), fp(q["p_maxt"]), fp(q["p_avgt"])]
        q = es[(es["era"] == era) & (es["costs"] == "gross_lag")].iloc[0]
        cells += [rng_t(q), int(q["n_sig_raw"])]
        body += row(*cells)
    tab = (r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lcrrrcrrrcr@{}}" "\n" r"\toprule" "\n"
           + r" & \multicolumn{4}{c}{Before costs} & \multicolumn{4}{c}{After 10 bp costs} & "
             r"\multicolumn{2}{c}{One-day lag} \\" "\n"
           + r"\cmidrule{2-5}\cmidrule{6-9}\cmidrule{10-11}" "\n"
           + row("Period", "$t$ range", "Sig.", r"$p_{\max}$", r"$p_{\mathrm{avg}}$", "$t$ range", "Sig.",
                 r"$p_{\max}$", r"$p_{\mathrm{avg}}$", "$t$ range", "Sig.")
           + r"\midrule" "\n" + body + r"\bottomrule" "\n" r"\end{tabular*}")
    note = ("US market, 56 designs. The walk-forward strategies are run once over the full sample and their "
            "out-of-sample days are then split by calendar period. $t$ range is the smallest and the largest of the "
            "56 $t$-statistics against buy-and-hold; Sig.\\ counts designs with $t>1.645$ (out of 56); "
            "$p_{\\max}$ and $p_{\\mathrm{avg}}$ are the bootstrap $p$-values of the max-$t$ and average-$t$ tests. "
            "In the last two columns, before costs, every trade is executed one day after its signal. "
            "Bold: $p<0.05$.")
    save("tab_eras", tab, note, es)


