"""Build the paper's tables as LaTeX (tables/tex/) plus machine-readable CSV (tables/csv/).

Each ``tables/tex/<name>.tex`` holds one ``tabular`` and its notes; ``paper/main.tex`` wraps it in a
``table`` float with the caption. Every cell is written from the result files.

Run from the replication folder:
    python tables/build_tables.py
"""
from __future__ import annotations

import json
import sys
