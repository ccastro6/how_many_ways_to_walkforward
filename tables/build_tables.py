SAMPLE_NAMES = {
    "us_1926": "US market", "developed": "Developed markets", "north_america": "North America",
    "europe": "Europe", "japan": "Japan", "asia_pac_ex_japan": "Asia Pacific ex Japan",
    "sp500_2016": r"S\&P 500 (price)",
}
ORDER = ["us_1926", "developed", "north_america", "europe", "japan", "asia_pac_ex_japan", "sp500_2016"]


def save(name, tabular, note, df=None):
    (HERE / "tex").mkdir(exist_ok=True)
    (HERE / "csv").mkdir(exist_ok=True)
    body = "% Generated by tables/build_tables.py; do not edit.\n" + tabular
    if note:
        body += ("\n\\par\\vspace{4pt}\n\\begin{minipage}{\\textwidth}\\footnotesize\\setstretch{1.0}\\emph{Notes.} "
                 + note + "\n\\end{minipage}\n")
    (HERE / "tex" / f"{name}.tex").write_text(body)
    if df is not None:
        df.to_csv(HERE / "csv" / f"{name}.csv", index=False)
    print("wrote", name)


def num(x, d=2):
    """A number with a typographic minus sign."""
    return f"{x:.{d}f}".replace("-", "$-$")


def fp(p, bold_below=0.05):
    """A p-value, bold when below ``bold_below``."""
    s = "$<$0.001" if p < 0.001 else f"{p:.3f}"
    return rf"\textbf{{{s}}}" if p < bold_below else s


def row(*cells):
    return " & ".join(str(c) for c in cells) + r" \\" + "\n"


def braces(values, fmt=str):
    return r"\{" + ", ".join(fmt(v) for v in values) + r"\}"


# ------------------------------------------------------------------ Table 1: rules
def tab_rules():
    from wfo import rules as R
    fc = R.family_counts()
    pct = lambda v: f"{100 * v:g}"
    body = row("Filter", f"filter $x$ (\\%): {', '.join(pct(x) for x in R.FILTER_X)}",
               f"plain; liquidation band $y$ (\\%) in {braces(R.FILTER_Y, pct)}, $y<x$; holding period $c$ in "
               f"{braces(R.FILTER_C)} days; reference extremes over the previous $e$ in {braces(R.FILTER_E)} days",
               fc["filter"])
    body += r"\addlinespace" + "\n"
    body += row("Moving average", f"fast $n$ in {braces(R.MA_FAST)}, slow $m$ in {braces(R.MA_SLOW)} days, $n<m$",
                f"plain; neutral band $b$ (\\%) in {braces(R.MA_BAND, pct)}", fc["ma"])
    body += r"\addlinespace" + "\n"
    body += row("Support and resistance", f"look-back $n$ in {braces(R.SR_N)} days",
                f"plain (held to the opposite signal); band $b$ (\\%) in {braces(R.SR_BAND, pct)}; holding period "
                f"$c$ in {braces(R.SR_C)} days", fc["sr"])
    body += r"\addlinespace" + "\n"
    body += row("Channel breakout", f"look-back $n$ in {braces(R.CB_N)} days, channel width $x$ (\\%) in "
                f"{braces(R.CB_X, pct)}", f"holding period $c$ in {braces(R.CB_C)} days", fc["cb"])
    body += r"\midrule" + "\n" + row("Total", "", "", R.N_RULES)
    tab = (r"\begin{tabularx}{\textwidth}{@{}>{\raggedright\arraybackslash}p{0.17\textwidth}"
           r">{\raggedright\arraybackslash}X>{\raggedright\arraybackslash}X r@{}}" "\n" r"\toprule" "\n"
           + row("Family", "Main parameters", "Variants", "Rules") + r"\midrule" "\n" + body
           + r"\bottomrule" "\n" r"\end{tabularx}")
    note = ("Four of the five rule families of Sullivan, Timmermann and White (1999), on closing prices; the fifth "
            "(on-balance volume) needs volume data. Each family's grid is a subset of theirs. Definitions are in "
            "Appendix~A. Positions are long, short or flat; a rule's position for day $t$ is decided at the close of "
            "day $t-1$.")
    df = pd.DataFrame([dict(name=r.name, family=r.family, params=str(r.params)) for r in R.RULES])
    save("tab_rules", tab, note, df)


# ------------------------------------------------------------------ Table 2: designs
def tab_designs():
    from wfo.splits import default_grid
    g = pd.DataFrame([c.as_dict() for c in default_grid()])
    n = g.groupby("scheme").size()
    body = (row("Rolling", "252, 504 or 1,008", "0", "fixed length $L$", r"$4\times 2$", n["rolling"])
            + row("Growing-rolling", "252, 504 or 1,008", "$h/2$", "starts at $L$, gains $G$ per block", r"$4\times 2$",
                  n["growing"])
            + row("Expanding", "all data since origin", "--", "start fixed at the origin", r"$4\times 2$", n["expanding"]))
    tab = (r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}llclcr@{}}" "\n" r"\toprule" "\n"
           + row("", "Initial training", "Growth $G$", "", r"Lengths $h$", "")
           + row("Scheme", "length $L$ (days)", "per block", "Training window", r"$\times$ gaps $g$", "Designs")
           + r"\midrule" "\n" + body + r"\bottomrule" "\n" r"\end{tabular*}")
    note = ("Every scheme is crossed with test-block lengths $h$ = 21, 63, 126 and 252 trading days (about one month, "
            "quarter, half-year and year) and a gap $g$ = 0 or 21 days between training and test, "
            f"for {len(g)} designs in total. All designs are scored on the same out-of-sample days; each day is scored "
            r"exactly once. Lengths are in trading days (252 $\approx$ one year).")
    save("tab_designs", tab, note, g)


# ------------------------------------------------------------------ Table 4: data
def tab_data():
    meta = json.loads((EMP / "meta.json").read_text())
    start = meta["oos_start_index"]
    files = {"us_1926": "us_market", "developed": "developed", "north_america": "north_america", "europe": "europe",
             "japan": "japan", "asia_pac_ex_japan": "asia_pac_ex_japan", "sp500_2016": "sp500_price"}
    recs, body = [], ""
    for s in ORDER:
        d = pd.read_csv(DATA / f"{files[s]}.csv")
        r = d["ret"].to_numpy()
        ex = r - d["rf"].fillna(0).to_numpy()
        rho = np.corrcoef(r[1:], r[:-1])[0, 1]
        rec = dict(series=SAMPLE_NAMES[s].replace("\\", ""), first=d["date"].iloc[0][:4], last=d["date"].iloc[-1][:4],
                   n=len(d), oos_first=d["date"].iloc[start][:7], ann_excess=252 * ex.mean(),
                   ann_vol=np.sqrt(252) * r.std(ddof=1), rho1=rho, source="FRED" if s == "sp500_2016" else "Ken French")
        recs.append(rec)
        body += row(SAMPLE_NAMES[s], rec["source"], f"{rec['first']}--{rec['last']}", f"{rec['n']:,}", rec["oos_first"],
                    num(100 * rec["ann_excess"], 1), num(100 * rec["ann_vol"], 1), num(rec["rho1"], 3))
    tab = (r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}llcrcrrr@{}}" "\n" r"\toprule" "\n"
           + row("", "", "", "", "First test", "Mean", "Volatility", "Autocorr.")
           + row("Series", "Source", "Span", "Days", "month", r"(\% p.a.)", r"(\% p.a.)", "(lag 1)")
           + r"\midrule" "\n" + body + r"\bottomrule" "\n" r"\end{tabular*}")
    note = (r"Daily total returns in US dollars (the S\&P 500 series is a price index without dividends, and its "
            "mean is a raw return). Mean is the annualised average return above the one-month T-bill. "
            "Autocorr.\\ is the first-order autocorrelation of daily returns: positive values in regional indices "
            "mostly reflect stale prices across time zones, a known source of spurious predictability. "
            f"The first test month leaves room for the longest training window (1,008 days), the gap and a "
            f"{BURN_IN}-day burn-in.")
    save("tab_data", tab, note, pd.DataFrame(recs))


